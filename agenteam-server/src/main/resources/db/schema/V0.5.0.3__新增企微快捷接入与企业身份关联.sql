CREATE TABLE wecom_setup_job (
  id varchar(100) NOT NULL,
  enterprise_id varchar(100) NOT NULL,
  owner_user_id varchar(100) NOT NULL,
  owner_session_version bigint NOT NULL,
  system_access boolean NOT NULL,
  enterprise_connection_id varchar(100) NOT NULL,
  enterprise_credential_revision bigint NOT NULL,
  connection_id varchar(100) DEFAULT NULL,
  bot_id varchar(100) DEFAULT NULL,
  input_json json NOT NULL,
  encrypted_json json DEFAULT NULL,
  platform_name varchar(200) DEFAULT NULL,
  stage varchar(32) NOT NULL,
  resume_stage varchar(32) DEFAULT NULL,
  expires_at datetime(3) DEFAULT NULL,
  next_attempt_at datetime(3) NOT NULL,
  error_code varchar(100) DEFAULT NULL,
  error_summary varchar(500) DEFAULT NULL,
  lease_owner varchar(100) DEFAULT NULL,
  lease_until datetime(3) DEFAULT NULL,
  revision bigint NOT NULL DEFAULT 1,
  created_at datetime(3) NOT NULL,
  updated_at datetime(3) NOT NULL,
  active_owner_key varchar(100) GENERATED ALWAYS AS
    (CASE WHEN stage IN ('completed','cancelled','expired') THEN NULL ELSE owner_user_id END) STORED,
  PRIMARY KEY (id),
  UNIQUE KEY uk_wecom_setup_active (enterprise_id, active_owner_key),
  KEY ix_wecom_setup_work (stage, next_attempt_at, lease_until),
  KEY ix_wecom_setup_owner (enterprise_id, owner_user_id, created_at),
  CONSTRAINT fk_wecom_setup_enterprise FOREIGN KEY (enterprise_id) REFERENCES enterprise(id),
  CONSTRAINT fk_wecom_setup_owner FOREIGN KEY (owner_user_id) REFERENCES app_user(id),
  CONSTRAINT fk_wecom_setup_parent FOREIGN KEY (enterprise_id, enterprise_connection_id) REFERENCES enterprise_integration(enterprise_id, id),
  CONSTRAINT fk_wecom_setup_connection FOREIGN KEY (enterprise_id, connection_id) REFERENCES enterprise_integration(enterprise_id, id),
  CONSTRAINT ck_wecom_setup_stage CHECK (stage IN ('queued','awaiting_scan','verifying','binding','completed','failed','cancelled','expired')),
  CONSTRAINT ck_wecom_setup_input CHECK (JSON_TYPE(input_json) = 'OBJECT'),
  CONSTRAINT ck_wecom_setup_revision CHECK (revision > 0 AND enterprise_credential_revision > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='企微机器人快捷创建进度';

CREATE TABLE wecom_bot_enterprise (
  id varchar(100) NOT NULL COMMENT '机器人接入编号',
  enterprise_id varchar(100) NOT NULL,
  enterprise_connection_id varchar(100) NOT NULL,
  external_tenant_id varchar(191) NOT NULL,
  bot_credential_revision bigint NOT NULL,
  enterprise_credential_revision bigint NOT NULL,
  owner_subject_hash char(64) NOT NULL,
  proof_method varchar(32) NOT NULL,
  verified_at datetime(3) NOT NULL,
  PRIMARY KEY (id),
  KEY ix_wecom_bot_parent (enterprise_id, enterprise_connection_id),
  CONSTRAINT fk_wecom_bot_connection FOREIGN KEY (enterprise_id, id) REFERENCES enterprise_integration(enterprise_id, id),
  CONSTRAINT fk_wecom_bot_parent FOREIGN KEY (enterprise_id, enterprise_connection_id) REFERENCES enterprise_integration(enterprise_id, id),
  CONSTRAINT ck_wecom_bot_proof CHECK (proof_method = 'cli_owner_conversion'),
  CONSTRAINT ck_wecom_bot_revisions CHECK (bot_credential_revision > 0 AND enterprise_credential_revision > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='企微机器人经平台身份转换确认的企业关联';

CREATE TABLE wecom_member_alias (
  id char(64) NOT NULL,
  enterprise_id varchar(100) NOT NULL,
  connection_id varchar(100) NOT NULL,
  enterprise_connection_id varchar(100) NOT NULL,
  bot_credential_revision bigint NOT NULL,
  enterprise_credential_revision bigint NOT NULL,
  subject_hash char(64) NOT NULL,
  member_id varchar(191) COLLATE utf8mb4_bin NOT NULL,
  expires_at datetime(3) NOT NULL,
  PRIMARY KEY (id),
  KEY ix_wecom_alias_expiry (expires_at),
  CONSTRAINT fk_wecom_alias_bot FOREIGN KEY (enterprise_id, connection_id) REFERENCES enterprise_integration(enterprise_id, id),
  CONSTRAINT fk_wecom_alias_parent FOREIGN KEY (enterprise_id, enterprise_connection_id) REFERENCES enterprise_integration(enterprise_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='企微平台成员编号的短期转换结果';
