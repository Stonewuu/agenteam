CREATE TABLE `model_usage_cost_item` (
    `id` VARCHAR(100) NOT NULL,
    `enterprise_id` VARCHAR(100) NOT NULL,
    `usage_record_id` VARCHAR(100) NOT NULL,
    `meter` VARCHAR(32) NOT NULL,
    `cache_ttl_seconds` INT NOT NULL DEFAULT 0,
    `quantity` BIGINT NOT NULL,
    `price_rate_id` VARCHAR(100) NOT NULL,
    `price_per_million_snapshot` DECIMAL(24,12) NOT NULL,
    `amount` DECIMAL(30,18) NOT NULL,
    `created_at` DATETIME(3) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_model_usage_cost_meter (enterprise_id, usage_record_id, meter, cache_ttl_seconds),
    CONSTRAINT fk_model_usage_cost_record FOREIGN KEY (enterprise_id, usage_record_id) REFERENCES model_usage_record (enterprise_id, id),
    CONSTRAINT fk_model_usage_cost_rate FOREIGN KEY (enterprise_id, price_rate_id) REFERENCES model_price_rate (enterprise_id, id),
    CONSTRAINT ck_model_usage_cost_meter CHECK (meter IN ('input_uncached','output','cache_read','cache_write')),
    CONSTRAINT ck_model_usage_cost_ttl CHECK (cache_ttl_seconds >= 0 AND (meter = 'cache_write' OR cache_ttl_seconds = 0)),
    CONSTRAINT ck_model_usage_cost_numbers CHECK (quantity BETWEEN 0 AND 100000000000 AND price_per_million_snapshot BETWEEN 0 AND 1000000 AND amount >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='一次请求某一互斥计量项的精确金额';
