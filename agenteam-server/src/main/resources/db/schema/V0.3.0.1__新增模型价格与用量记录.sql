-- 新增模型价格与用量记录；不修改历史记录，不自动设置厂商价格。
ALTER TABLE model_provider DROP CHECK ck_model_provider_1, ADD CONSTRAINT ck_model_provider_1 CHECK (protocol IN ('openai','openai_responses','anthropic','gemini'));

CREATE TABLE `model_price_version` (
    `id` VARCHAR(100) NOT NULL,
    `enterprise_id` VARCHAR(100) NOT NULL,
    `model_profile_id` VARCHAR(100) NOT NULL,
    `version_no` BIGINT NOT NULL,
    `status` VARCHAR(16) NOT NULL DEFAULT 'draft',
    `currency` CHAR(3) NOT NULL,
    `timezone` VARCHAR(64) NOT NULL,
    `effective_from` DATETIME(3) NULL,
    `calendar_valid_through` DATE NULL,
    `context_basis` VARCHAR(32) NOT NULL DEFAULT 'total_input',
    `source_reference` VARCHAR(2048) NULL,
    `source_checked_at` DATETIME(3) NULL,
    `note` VARCHAR(500) NULL,
    `revision` BIGINT NOT NULL DEFAULT 1,
    `created_by` VARCHAR(100) NOT NULL,
    `published_by` VARCHAR(100) NULL,
    `created_at` DATETIME(3) NOT NULL,
    `updated_at` DATETIME(3) NOT NULL,
    `published_at` DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_model_price_version_scope (enterprise_id, id),
    UNIQUE KEY uk_model_price_version_model (enterprise_id, model_profile_id, id),
    UNIQUE KEY uk_model_price_version_no (enterprise_id, model_profile_id, version_no),
    UNIQUE KEY uk_model_price_version_effective (enterprise_id, model_profile_id, effective_from),
    KEY idx_model_price_current (enterprise_id, model_profile_id, status, effective_from),
    CONSTRAINT fk_model_price_version_model FOREIGN KEY (enterprise_id, model_profile_id) REFERENCES model_profile (enterprise_id, id),
    CONSTRAINT ck_model_price_version_status CHECK (status IN ('draft','published')),
    CONSTRAINT ck_model_price_version_basis CHECK (context_basis = 'total_input'),
    CONSTRAINT ck_model_price_version_numbers CHECK (version_no > 0 AND revision > 0),
    CONSTRAINT ck_model_price_version_publication CHECK ((status = 'draft' AND effective_from IS NULL AND published_at IS NULL AND published_by IS NULL) OR (status = 'published' AND effective_from IS NOT NULL AND published_at IS NOT NULL AND published_by IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='模型价格版本，发布后保留完整条件与价格';

CREATE TABLE `model_price_rule` (
    `id` VARCHAR(100) NOT NULL,
    `enterprise_id` VARCHAR(100) NOT NULL,
    `price_version_id` VARCHAR(100) NOT NULL,
    `name` VARCHAR(100) NOT NULL,
    `priority` INT NOT NULL,
    `is_default` TINYINT NOT NULL DEFAULT 0,
    `context_min_tokens` BIGINT NOT NULL DEFAULT 0,
    `context_max_tokens` BIGINT NULL,
    `service_tier` VARCHAR(32) NOT NULL DEFAULT 'standard',
    `display_order` INT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_model_price_rule_scope (enterprise_id, id),
    UNIQUE KEY uk_model_price_rule_version (enterprise_id, price_version_id, id),
    UNIQUE KEY uk_model_price_rule_name (enterprise_id, price_version_id, name),
    KEY idx_model_price_rule_priority (enterprise_id, price_version_id, priority),
    CONSTRAINT fk_model_price_rule_version FOREIGN KEY (enterprise_id, price_version_id) REFERENCES model_price_version (enterprise_id, id),
    CONSTRAINT ck_model_price_rule_context CHECK (context_min_tokens >= 0 AND (context_max_tokens IS NULL OR context_max_tokens > context_min_tokens)),
    CONSTRAINT ck_model_price_rule_priority CHECK (priority BETWEEN 0 AND 1000 AND is_default IN (0,1) AND (is_default = 0 OR priority = 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='同一价格版本中的完整匹配条件';

CREATE TABLE `model_price_rule_time` (
    `id` VARCHAR(100) NOT NULL,
    `enterprise_id` VARCHAR(100) NOT NULL,
    `price_rule_id` VARCHAR(100) NOT NULL,
    `weekday` TINYINT NOT NULL,
    `start_minute` SMALLINT NOT NULL,
    `end_minute` SMALLINT NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_model_price_time_interval (enterprise_id, price_rule_id, weekday, start_minute, end_minute),
    CONSTRAINT fk_model_price_time_rule FOREIGN KEY (enterprise_id, price_rule_id) REFERENCES model_price_rule (enterprise_id, id),
    CONSTRAINT ck_model_price_time_range CHECK (weekday BETWEEN 1 AND 7 AND start_minute >= 0 AND end_minute <= 1440 AND end_minute > start_minute)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='价格规则在本地星期中的有效分钟区间';

CREATE TABLE `model_price_rule_date` (
    `id` VARCHAR(100) NOT NULL,
    `enterprise_id` VARCHAR(100) NOT NULL,
    `price_rule_id` VARCHAR(100) NOT NULL,
    `local_date` DATE NOT NULL,
    `kind` VARCHAR(8) NOT NULL,
    `note` VARCHAR(100) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_model_price_date (enterprise_id, price_rule_id, local_date),
    CONSTRAINT fk_model_price_date_rule FOREIGN KEY (enterprise_id, price_rule_id) REFERENCES model_price_rule (enterprise_id, id),
    CONSTRAINT ck_model_price_date_kind CHECK (kind IN ('include','exclude'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='价格规则明确包含或排除的本地日期';

CREATE TABLE `model_price_rate` (
    `id` VARCHAR(100) NOT NULL,
    `enterprise_id` VARCHAR(100) NOT NULL,
    `price_rule_id` VARCHAR(100) NOT NULL,
    `meter` VARCHAR(32) NOT NULL,
    `cache_ttl_seconds` INT NOT NULL DEFAULT 0,
    `price_per_million` DECIMAL(24,12) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_model_price_rate_scope (enterprise_id, id),
    UNIQUE KEY uk_model_price_rate_meter (enterprise_id, price_rule_id, meter, cache_ttl_seconds),
    CONSTRAINT fk_model_price_rate_rule FOREIGN KEY (enterprise_id, price_rule_id) REFERENCES model_price_rule (enterprise_id, id),
    CONSTRAINT ck_model_price_rate_meter CHECK (meter IN ('input_uncached','output','cache_read','cache_write')),
    CONSTRAINT ck_model_price_rate_ttl CHECK (cache_ttl_seconds >= 0 AND (meter = 'cache_write' OR cache_ttl_seconds = 0)),
    CONSTRAINT ck_model_price_rate_amount CHECK (price_per_million BETWEEN 0 AND 1000000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='各计量项按每百万单位保存的单价';

